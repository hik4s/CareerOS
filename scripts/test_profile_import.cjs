'use strict';
const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const source = fs.readFileSync('app/cloud/static/app.js', 'utf8');
const context = vm.createContext({});
const start = source.indexOf('function applyProfileSuggestions(');
assert(start >= 0, 'Profile import must provide the form application behavior');
vm.runInContext(source.slice(start, source.indexOf('function renderProfile()', start)), context);
const fields = {full_name:{value:'Nome editado'}, email:{value:'existing@example.com'},
  skills:{value:'SQL'}, term:{value:'4'}, evidence:{value:'[]'}};
context.form = {elements:{namedItem:name=>fields[name]}};
context.suggestions = {full_name:'Ana Souza',email:'ana@example.com',skills:['Python','React'],term:2,evidence:[{name:'Untrusted'}]};
context.selected = ['skills', 'term', 'evidence', '__proto__'];
vm.runInContext('applyProfileSuggestions(form, suggestions, selected)', context);
assert.equal(fields.full_name.value, 'Nome editado', 'Unselected current edits survive');
assert.equal(fields.email.value, 'existing@example.com');
assert.equal(fields.skills.value, 'Python, React');
assert.equal(fields.term.value, '2');
assert.equal(fields.evidence.value, '[]', 'Only allowlisted parsed fields can be applied');
context.selected = ['full_name'];
vm.runInContext('applyProfileSuggestions(form, suggestions, selected)', context);
assert.equal(fields.full_name.value, 'Ana Souza', 'Explicit selection permits replacement');
context.baseline = {full_name:'Ana Souza'};
fields.full_name.value = 'Edição após a prévia';
vm.runInContext('applyProfileSuggestions(form, suggestions, selected, baseline)', context);
assert.equal(fields.full_name.value, 'Edição após a prévia', 'Edits after preview must not be silently overwritten');
context.baseline.full_name = fields.full_name.value;
vm.runInContext('applyProfileSuggestions(form, suggestions, selected, baseline)', context);
assert.equal(fields.full_name.value, 'Ana Souza', 'Confirming replacement against the new value allows overwrite');
console.log('PASS selected suggestions fill form, existing edits survive, unsupported fields ignored');
